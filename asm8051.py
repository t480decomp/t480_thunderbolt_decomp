#!/usr/bin/env python3
"""asm8051.py - assemble the three 8051 listings and compare them with the vendor image.

    listing  ->  sdas8051 source (mk_sdas.py)  ->  sdas8051  ->  sdld  ->  Intel HEX  ->  bytes

Writes the assembled code to build/regen/ so mkimage.py can splice it into the image, and
reports any byte where the listing and the fetched vendor image disagree -- which is exactly
what you see after editing a listing.
"""
import os
import subprocess
import sys
import tempfile

import toolchain

HERE = os.path.dirname(os.path.abspath(__file__))
SDAS = None
SDLD = None


def parse_ihx(path):
    out = {}
    for line in open(path):
        line = line.strip()
        if not line.startswith(":"):
            continue
        b = bytes.fromhex(line[1:])
        n, addr, kind = b[0], (b[1] << 8) | b[2], b[3]
        if kind == 0:
            for i in range(n):
                out[addr + i] = b[4 + i]
    return out


IMAGE = os.path.join(HERE, "build", "TBT.bin")


def verify(listing, base, blobname, tmp, code_off=0x200):
    """base = file offset of logical address 0; code_off = first byte the listing assembles"""
    src = os.path.join(tmp, os.path.basename(listing).replace(".asm", ".s"))
    subprocess.run([sys.executable, os.path.join(HERE, "mk_sdas.py"), listing, src],
                   check=True, capture_output=True)
    stem = src[:-2]
    subprocess.run([SDAS, "-plosgff", src], cwd=tmp, check=True, capture_output=True)
    subprocess.run([SDLD, "-i", os.path.basename(stem) + ".rel"], cwd=tmp, check=True, capture_output=True)
    got = parse_ihx(stem + ".ihx")
    orig = open(IMAGE, "rb").read()[base:]
    image = os.path.basename(listing)
    # keep the regenerated bytes so the repack step can rebuild the container
    regen_dir = os.path.join(HERE, "build", "regen")
    os.makedirs(regen_dir, exist_ok=True)
    if got:
        blob = bytearray(max(got) + 1)
        for a, v in got.items():
            blob[a] = v
        with open(os.path.join(regen_dir, blobname), "wb") as f:
            f.write(bytes(blob))
    lo, hi = min(got), max(got)
    bad = [i for i in sorted(got) if got[i] != orig[i]]
    gaps = [i for i in range(lo, hi + 1) if i not in got]
    body = max(got) + 1 - code_off
    return {
        "image": image,
        "regenerated": len(got),
        "body": body,
        "range": (lo, hi),
        "mismatches": bad,
        "gaps": gaps,
        "exact": not bad and not gaps and len(got) == body,
    }


def main():
    global SDAS, SDLD
    SDAS = toolchain.require(toolchain.sdas8051(), "sdas8051")
    SDLD = toolchain.require(toolchain.sdld(), "sdld")
    pairs = [("dp_out.asm", 0x6254, "dp_out_u_code.bin", 0x200),
             ("dp_in.asm", 0xC256, "dp_in_u_code.bin", 0x200),
             ("lc.asm", 0x14258, "lc_u_code.bin", 0x000)]
    ok = True
    with tempfile.TemporaryDirectory() as tmp:
        for listing, base, blobname, code_off in pairs:
            r = verify(os.path.join(HERE, listing), base, blobname, tmp, code_off)
            print("%-12s body=%6d regenerated=%6d range=0x%04X-0x%04X  differs from vendor=%d gaps=%d  %s"
                  % (r["image"], r["body"], r["regenerated"], r["range"][0], r["range"][1],
                     len(r["mismatches"]), len(r["gaps"]),
                     "identical" if r["exact"] else "edited"))
            ok = ok and r["exact"]
    print("\nRESULT:", "all 8051 images match the vendor image" if ok else "listings differ from vendor (edits applied)")
    if "--strict" in sys.argv and not ok:
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
